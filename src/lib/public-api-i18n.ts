export type PublicLocale = "id" | "en" | "ar" | "fr" | "ja";

export function normalizePublicLocale(locale?: string | null): PublicLocale {
  if (!locale) return "id";
  const base = locale.toLowerCase().split("-")[0];
  if (base === "en" || base === "ar" || base === "fr" || base === "ja" || base === "id") {
    return base;
  }
  return "id";
}

export function getLocaleFromRequest(req: Request, explicitLocale?: string | null): PublicLocale {
  if (explicitLocale) return normalizePublicLocale(explicitLocale);
  const accept = req.headers.get("accept-language");
  if (accept) {
    const first = accept.split(",")[0]?.trim();
    if (first) return normalizePublicLocale(first);
  }
  return "id";
}

