export function getPublicApiMessage(
  locale: PublicLocale | string | null | undefined,
  key: string,
  params?: MsgParams
): string {
  const norm = normalizePublicLocale(locale);
  const template = API_MESSAGES[norm]?.[key] || API_MESSAGES.id[key] || key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, k) =>
    params[k] !== undefined ? String(params[k]) : ""
  );
}
